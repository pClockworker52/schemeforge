"""Regenerate the index table at the top of docs/DECISIONS.md from its '## ' entry headings.

Usage: python scripts/decisions_index.py. The "Changed by" column lists only explicit changes recorded in CHANGED.
"""

import re
from pathlib import Path

PATH = Path(__file__).resolve().parents[1] / "docs" / "DECISIONS.md"
CHANGED = {  # entry heading -> (what changed, heading of the later entry that changed it)
    "2026-10-30 — Benchmark release (Peter)": (
        "licence part", "2026-10-30 — Licence: GPL-3.0-or-later instead of MIT (Peter)"),
    "2026-11-03 — Cold-spray track: local first (Peter)": (
        "solver part", "2026-11-03 — Main impact solver: OpenCourant instead of OpenRadioss (Peter)"),
}
TRACKS = {
    "2026-10-20 — Engine: build our own (OpenEvolve and ShinkaEvolve reviewed)": "repository",
    "2026-11-03 — Arena 2 paused; cold-spray question opened (Peter)": "Arena 2 / cold spray",
}

COLD_SPRAY_KEYS = (
    "Cold-spray", "OpenCourant", "simulation route", "SPH", "Blind test", "Cold spray", "CS-1", "Campaign trigger",
)


def slug(heading: str) -> str:
    """GitHub-style anchor of a heading."""
    return re.sub(r"[^\w\- ]", "", heading.lower().strip()).replace(" ", "-")


def track(h: str) -> str:
    if h in TRACKS:
        return TRACKS[h]
    if any(k in h for k in COLD_SPRAY_KEYS):
        return "cold spray"
    if any(k in h for k in ("Arena 2", "Phase 6", "Each arena")):
        return "Arena 2 / all arenas"
    if any(k in h for k in ("WSL", "Venv", "Licence", "Benchmark release", "Plan v1.1", "Appendices")):
        return "repository"
    return "Arena 1 (euler1d)"


def main() -> None:
    text = PATH.read_text()
    body = re.sub(r"\A# DECISIONS\n\n## Index\n.*?(?=\n## (?!Index))", "", text, flags=re.S).lstrip("\n")
    if body.startswith("# DECISIONS"):
        body = body.split("\n", 1)[1].lstrip("\n")
    heads = re.findall(r"^## (.+)$", body, re.M)
    lines = ["## Index", "",
             "One line per entry, in order. Generated by `scripts/decisions_index.py` from the `##` headings; "
             "regenerate when an entry is added.",
             "\"Changed by\" lists only changes that a later entry states explicitly; all other entries are in force "
             "as written.", "", "| Date | Decision | Track | Changed by |", "|---|---|---|---|"]
    for h in heads:
        date, title = h.split(" — ", 1)
        ch = ""
        if h in CHANGED:
            what, by = CHANGED[h]
            ch = f"{what}: [{by.split(' — ', 1)[1].replace(' (Peter)', '')}](#{slug(by)})"
        lines.append(f"| {date} | [{title}](#{slug(h)}) | {track(h)} | {ch} |")
    PATH.write_text("# DECISIONS\n\n" + "\n".join(lines) + "\n\n" + body)
    print(len(heads), "entries")


if __name__ == "__main__":
    main()
